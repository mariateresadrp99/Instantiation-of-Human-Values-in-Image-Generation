"""Turn taxonomy gaps into auxiliary scenes for steering (Sec. 6).

For the 20 value items with the lowest N_eff^vp across the open-weight models, an LLM receives the
value prompt, the model's dominant visual prototypes and the taxonomy categories, and writes 20
concrete scenes that express the same value through under-represented social configurations.

    python generate_auxiliary_scenes.py --breadth results/breadth.csv \
        --assignments results/clustering/assignments.csv \
        --labels results/clustering/prototype_labels.csv --output results/aux_scenes.json
"""

import argparse
import json
import re
from pathlib import Path

import pandas as pd

from utils import llm, read_prompts

PROMPT = """The goal is to broaden how a T2I model visually instantiates an abstract
human value. Given an original value prompt, the dominant visual prototypes
currently produced by the model, and the categories in a social-configuration
taxonomy, generate concrete auxiliary scenes that express the same value
through meaningful combinations of taxonomy categories.

Original value prompt:
{base_prompt}

Value item:
{value_item}

Dominant visual prototypes currently generated by the model:
{dominant_visual_prototypes}

Social-configuration taxonomy:
Setting: Institutional, Vernacular, Domestic, Natural
Sociality: Individual, Dyadic, Collective
Mode of Engagement: Presentational, Cognitive-Communicative,
                    Receptive-Consumptive, Embodied-Practical
Social Register: Formal, Affluence-Coded, Occupational-Service,
                 Vernacular/Everyday, Specialized/Recreational,
                 Hardship-Coded

Instructions:
- Generate {n} auxiliary scene prototypes.
- Each prototype should be a short, concrete visual scene description.
- Each scene should be used as a prompt for a T2I model.
- Combine taxonomy categories into meaningful and visually plausible
  social configurations.
- Do not simply list taxonomy labels; describe coherent scenes.
- Output only a numbered list of scene descriptions.

Example:
For the value prompt "a successful person", a possible auxiliary scene is:
"a person spending time with their family at home"
This combines Domestic setting, Collective sociality, Embodied-Practical
engagement, Vernacular/Everyday register."""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--breadth", required=True)
    ap.add_argument("--assignments", required=True)
    ap.add_argument("--labels", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("--csv", default="prompts.csv")
    ap.add_argument("--models", nargs="+", default=["flux2", "qwen", "sd35"])
    ap.add_argument("--llm_url", default="http://localhost:8000/v1")
    args = ap.parse_args()

    prompts = {r["value"]: r for r in read_prompts(args.csv)}
    b = pd.read_csv(args.breadth)
    b = b[(b.prompt_type == "positive_prompt") & (b.condition == "original") & b.model.isin(args.models)]
    values = b.groupby("value")["neff_vp"].mean().nsmallest(20).index
    df = pd.read_csv(args.assignments).merge(pd.read_csv(args.labels), on="cluster")
    df = df[df.prompt_type == "positive_prompt"]

    scenes = {}
    for model in args.models:
        for value in values:
            top = df[(df.model == model) & (df.value == value)]["visual_prototype_label"].value_counts(normalize=True)
            protos = "\n".join(f"- {label} ({100 * share:.0f}%)" for label, share in top.head(5).items())
            answer = llm(PROMPT.format(base_prompt=prompts[value]["positive_prompt"], value_item=value.replace("_", " "),
                                       dominant_visual_prototypes=protos, n=20), base_url=args.llm_url, temperature=0.7)
            found = [m.strip(' "') for m in re.findall(r"^\s*\d+[.)]\s*(.+)$", answer, re.M)]
            scenes.setdefault(model, {})[value] = {"base_prompt": prompts[value]["positive_prompt"],
                                                   "schwartz_domain": prompts[value]["schwartz_domain"],
                                                   "scenes": found[:20]}
            print(f"{model}/{value}: {len(found)} scenes, e.g. {found[:1]}")
    Path(args.output).write_text(json.dumps(scenes, indent=1))


if __name__ == "__main__":
    main()
